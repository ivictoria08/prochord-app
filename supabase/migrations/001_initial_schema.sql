-- Ejecutar una vez en el SQL Editor de un proyecto nuevo de Supabase.
begin;

create table public.canciones (
  id integer generated by default as identity primary key,
  titulo text not null check (length(btrim(titulo)) > 0),
  tono_base text not null check (tono_base ~ '^[A-G](#|b)?m?$'),
  bpm integer check (bpm > 0),
  compas text not null default '4/4' check (compas ~ '^[1-9][0-9]*/(2|4|8|16)$'),
  estilo text not null default 'Alabanza' check (estilo in ('Alabanza', 'Adoración', 'Júbilo')),
  letra_acordes text not null check (length(btrim(letra_acordes)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Un único setlist, con una posición y una aparición por canción.
create table public.setlist (
  orden integer primary key check (orden > 0),
  cancion_id integer not null unique references public.canciones(id) on delete cascade
);

-- Supabase Auth administra correo, contraseña y sesiones en auth.users.
-- Esta tabla únicamente asigna permisos; no contiene hashes de contraseñas.
create table public.administradores (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create function public.actualizar_fecha_cancion()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger canciones_updated_at before update on public.canciones
for each row execute function public.actualizar_fecha_cancion();

create function public.es_administrador()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.administradores where user_id = (select auth.uid()));
$$;

alter table public.canciones enable row level security;
alter table public.setlist enable row level security;
alter table public.administradores enable row level security;

revoke all on public.canciones, public.setlist, public.administradores from anon, authenticated;
grant select on public.canciones, public.setlist to anon, authenticated;
grant insert, update, delete on public.canciones to authenticated;
grant usage, select on sequence public.canciones_id_seq to authenticated;
grant select on public.administradores to authenticated;

revoke all on function public.es_administrador() from public;
grant execute on function public.es_administrador() to anon, authenticated;
revoke all on function public.actualizar_fecha_cancion() from public;

create policy "leer setlist" on public.setlist for select to anon, authenticated using (true);

create policy "leer canciones publicadas o catalogo admin" on public.canciones
for select to anon, authenticated using (
  (select public.es_administrador())
  or exists (select 1 from public.setlist where cancion_id = canciones.id)
);

create policy "crear canciones admin" on public.canciones
for insert to authenticated with check ((select public.es_administrador()));
create policy "editar canciones admin" on public.canciones
for update to authenticated using ((select public.es_administrador()))
with check ((select public.es_administrador()));
create policy "eliminar canciones admin" on public.canciones
for delete to authenticated using ((select public.es_administrador()));
create policy "consultar mi permiso" on public.administradores
for select to authenticated using (user_id = (select auth.uid()));

-- Solo esta función permite cambiar el setlist desde el cliente.
-- La sustitución es atómica y las escrituras concurrentes se serializan.
create function public.guardar_setlist(canciones_ids integer[])
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.es_administrador() then
    raise exception 'No tienes permisos de administrador.' using errcode = '42501';
  end if;
  if canciones_ids is null or cardinality(canciones_ids) > 500
     or coalesce(array_ndims(canciones_ids), 1) <> 1
     or exists (select 1 from unnest(canciones_ids) as ids(id) where id is null or id <= 0) then
    raise exception 'Envía una lista de hasta 500 IDs positivos.' using errcode = '22023';
  end if;
  if (select count(distinct id) from unnest(canciones_ids) as ids(id)) <> cardinality(canciones_ids) then
    raise exception 'No repitas canciones en el setlist.' using errcode = '22023';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(752041);
  if (select count(*) from public.canciones where id = any(canciones_ids)) <> cardinality(canciones_ids) then
    raise exception 'Una o más canciones no existen.' using errcode = '22023';
  end if;
  -- Todas las posiciones son positivas; el filtro permite reemplazar el setlist
  -- sin un DELETE sin WHERE, rechazado por la protección de Supabase.
  delete from public.setlist where orden > 0;
  insert into public.setlist (cancion_id, orden)
    select id, posicion::integer from unnest(canciones_ids) with ordinality as ids(id, posicion);
end;
$$;

revoke all on function public.guardar_setlist(integer[]) from public, anon;
grant execute on function public.guardar_setlist(integer[]) to authenticated;

commit;
